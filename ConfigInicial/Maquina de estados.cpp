// Moves/alters the camera positions based on user input
void DoMovement()
{

	// Camera controls
	if (keys[GLFW_KEY_W] || keys[GLFW_KEY_UP])
	{
		camera.ProcessKeyboard(FORWARD, deltaTime);

	}

	if (keys[GLFW_KEY_S] || keys[GLFW_KEY_DOWN])
	{
		camera.ProcessKeyboard(BACKWARD, deltaTime);


	}

	if (keys[GLFW_KEY_A] || keys[GLFW_KEY_LEFT])
	{
		camera.ProcessKeyboard(LEFT, deltaTime);


	}

	if (keys[GLFW_KEY_D] || keys[GLFW_KEY_RIGHT])
	{
		camera.ProcessKeyboard(RIGHT, deltaTime);


	}

	if (keys[GLFW_KEY_T])
	{
		pointLightPositions[0].x += 0.01f;
	}
	if (keys[GLFW_KEY_G])
	{
		pointLightPositions[0].x -= 0.01f;
	}

	if (keys[GLFW_KEY_Y])
	{
		pointLightPositions[0].y += 0.01f;
	}

	if (keys[GLFW_KEY_H])
	{
		pointLightPositions[0].y -= 0.01f;
	}
	if (keys[GLFW_KEY_U])
	{
		pointLightPositions[0].z -= 0.1f;
	}
	if (keys[GLFW_KEY_J])
	{
		pointLightPositions[0].z += 0.01f;
	}

}

// Is called whenever a key is pressed/released via GLFW
void KeyCallback(GLFWwindow* window, int key, int scancode, int action, int mode)
{
	if (GLFW_KEY_ESCAPE == key && GLFW_PRESS == action)
	{
		glfwSetWindowShouldClose(window, GL_TRUE);
	}

	if (key >= 0 && key < 1024)
	{
		if (action == GLFW_PRESS)
		{
			keys[key] = true;
		}
		else if (action == GLFW_RELEASE)
		{
			keys[key] = false;
		}
	}

	if (keys[GLFW_KEY_SPACE])
	{
		active = !active;
		if (active)
		{
			Light1 = glm::vec3(0.2f, 0.8f, 1.0f);

		}
		else
		{
			Light1 = glm::vec3(0);//Cuado es solo un valor en los 3 vectores pueden dejar solo una componente
		}
	}
	if (keys[GLFW_KEY_N])
	{
		AnimBall = !AnimBall;

	}
	if (keys[GLFW_KEY_B])
	{
		// Inicia el recorrido solo si el perro esta quieto en el centro
		if (dogAnim == QUIETO)
		{
			puntoActual = 0;
			dogAnim = CAMINANDO;
		}
	}
}

// Se mueve poco a poco a un punto 
float Acercar(float actual, float objetivo, float paso)
{
	if (actual < objetivo)
	{
		actual += paso;
		if (actual > objetivo) actual = objetivo;
	}
	else
	{
		actual -= paso;
		if (actual < objetivo) actual = objetivo;
	}
	return actual;
}

// Calcula hacia donde debe girar el perro al llegar a un punto 
void PrepararGiro()
{
	float angulo;
	if (puntoActual < NUM_PUNTOS - 1)
	{
		// Mira hacia el siguiente punto 
		glm::vec3 dir = ruta[puntoActual + 1] - dogPos;
		angulo = glm::degrees(atan2(dir.x, dir.z));
	}
	else
	{
		// Ultimo punto (centro)
		angulo = 0.0f;
	}

	// Giro mas corto
	while (angulo - dogRot > 180.0f)  angulo -= 360.0f;
	while (angulo - dogRot < -180.0f) angulo += 360.0f;

	rotObjetivo = angulo;
	dirGiro = (rotObjetivo < dogRot) ? -1.0f : 1.0f;
	dogAnim = GIRANDO;
}

void Animation() {
	if (AnimBall)
	{
		rotBall += 0.4f;
		//printf("%f", rotBall);
	}

	if (AnimDog)
	{
		rotDog -= 0.6f;
		//printf("%f", rotBall);
	}

	// Limitar deltaTime para evitar saltos si un cuadro tarda mucho
	float dt = deltaTime;
	if (dt > 0.05f) dt = 0.05f;

	// Estado quieto 
	if (dogAnim == QUIETO)
	{
		// Todo regresa a la pose de reposo
		ampCaminar = Acercar(ampCaminar, 0.0f, 2.0f * dt);
		ampGiro = Acercar(ampGiro, 0.0f, 2.0f * dt);
		headTurn = Acercar(headTurn, 0.0f, 60.0f * dt);
	}

	// Estado caminando 
	else if (dogAnim == CAMINANDO)
	{
		glm::vec3 destino = ruta[puntoActual];
		glm::vec3 faltante = destino - dogPos;
		float distancia = glm::length(faltante);

		// Acelera al iniciar y frena un poco al llegar a la esquina
		float velObjetivo = glm::clamp(distancia / 0.4f, 0.25f, 1.0f);
		ampCaminar = Acercar(ampCaminar, velObjetivo, 2.5f * dt);
		ampGiro = Acercar(ampGiro, 0.0f, 3.0f * dt);
		headTurn = Acercar(headTurn, 0.0f, 50.0f * dt); 

		float avance = VEL_CAMINAR * ampCaminar * dt;
		if (avance >= distancia)
		{
			// Llego al punto: cambia al estado de giro
			dogPos = destino;
			PrepararGiro();
		}
		else
		{
			dogPos += (faltante / distancia) * avance;
		}
	}

	// Estado girando 
	else if (dogAnim == GIRANDO)
	{
		ampCaminar = Acercar(ampCaminar, 0.0f, 3.0f * dt);

		// voltea hacia el lado del giro
		headTurn = Acercar(headTurn, dirGiro * GIRO_CABEZA, 70.0f * dt);
		bool cabezaVolteada = fabs(headTurn - dirGiro * GIRO_CABEZA) < 0.5f;

		if (cabezaVolteada)
			ampGiro = Acercar(ampGiro, 1.0f, 3.0f * dt);

		// El cuerpo gira, empieza despacio y frena al final del giro
		float faltaGirar = fabs(rotObjetivo - dogRot);
		float vel = VEL_GIRO * ampGiro * glm::clamp(faltaGirar / 30.0f, 0.3f, 1.0f);
		float paso = vel * dt;

		if (!cabezaVolteada)
		{
			// Mientras la cabeza voltea, el cuerpo espera
		}
		else if (faltaGirar <= paso)
		{
			dogRot = rotObjetivo;
			puntoActual++;
			if (puntoActual >= NUM_PUNTOS)
			{
				// Termino el recorrido en el centro
				dogRot = fmod(dogRot, 360.0f);
				if (fabs(dogRot) < 0.01f) dogRot = 0.0f;
				dogAnim = QUIETO;
			}
			else
			{
				dogAnim = CAMINANDO;
			}
		}
		else
		{
			dogRot += dirGiro * paso;
		}
	}

	// El ciclo avanza segun que tanto camina o gira
	ciclo += (FREC_CAMINAR * ampCaminar + FREC_GIRO * ampGiro) * dt;

	// Caminar con patas en diagonal 
	// Girar cada pata se mueve en un tiempo distinto 
	legFL = ampCaminar * AMP_CAMINAR * sin(ciclo)
		+ ampGiro * AMP_GIRO * sin(ciclo);
	legFR = ampCaminar * AMP_CAMINAR * sin(ciclo + PI)
		+ ampGiro * AMP_GIRO * sin(ciclo + PI / 2.0f);
	legBR = ampCaminar * AMP_CAMINAR * sin(ciclo)
		+ ampGiro * AMP_GIRO * sin(ciclo + PI);
	legBL = ampCaminar * AMP_CAMINAR * sin(ciclo + PI)
		+ ampGiro * AMP_GIRO * sin(ciclo + 3.0f * PI / 2.0f);
	// La cabeza sube y baja; girar: la cabeza queda quieta mirando al giro
	headNod = ampCaminar * 4.0f * sin(2.0f * ciclo);
	// La cola se mueve; girar: la cola se inclina al lado contrario del giro
	tail = ampCaminar * 15.0f * sin(2.0f * ciclo)
		- ampGiro * dirGiro * 20.0f;
	dogBob = ampCaminar * 0.006f * fabs(sin(ciclo));
}

void MouseCallback(GLFWwindow* window, double xPos, double yPos)
{
	if (firstMouse)
	{
		lastX = xPos;
		lastY = yPos;
		firstMouse = false;
	}

	GLfloat xOffset = xPos - lastX;
	GLfloat yOffset = lastY - yPos;  // Reversed since y-coordinates go from bottom to left

	lastX = xPos;
	lastY = yPos;

	camera.ProcessMouseMovement(xOffset, yOffset);
}